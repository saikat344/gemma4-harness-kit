#!/usr/bin/env python3
"""Compose the sandbox Dockerfile from the competition's own docker/Dockerfile.public (your Kaggle download).

The competition's Dockerfile is not redistributed with this kit. Stage `official` is that file verbatim, except
for pins, applied here at build time:
  * the base image `python:3.13-slim` gets the digest that resolved on 2026-11-02 and the stage name `official`;
  * the unpinned packages of its `pip install` line get the versions that resolved on 2026-11-02.
Every other line is copied unchanged. Stage `final` (Dockerfile.fixes, ours) is appended.

    python harness/sandbox/compose_dockerfile.py --public data/kaggle/docker/Dockerfile.public --out ctx/Dockerfile
    python harness/sandbox/compose_dockerfile.py --public data/kaggle/docker/Dockerfile.public --diff

`--diff` prints a unified diff of the public file against stage `official`: only the pinned lines change.
The input's sha256 must match the file this was built against (override with --allow-other-sha256).
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PUBLIC_SHA256 = 'c92dfd9cd9ce019c4910a5334d6ecac606b612ec736a933b4af36da9c6fdf06c'
BASE = 'python:3.13-slim'
BASE_DIGEST = 'sha256:ae14d4ce8771606477a81446e7ef429edd6762305fc50c84507c1041fa8285d1'
# versions that resolved on 2026-11-02 for the packages the public file leaves unpinned
PIP_PINS = {
    'pytest': '9.2.0', 'typer': '0.27.3', 'pdm-backend': '2.5.0', 'setuptools': '84.2.1', 'wheel': '0.48.0',
    'poetry-core': '2.5.0', 'hatchling': '1.33.0', 'flit-core': '4.2.0', 'editables': '0.6',
}


class ComposeError(RuntimeError):
    pass


def pin_official(public: str) -> str:
    lines = public.splitlines(keepends=True)
    out, n_from, n_pip = [], 0, 0
    for ln in lines:
        if re.fullmatch(rf'FROM {re.escape(BASE)}\s*', ln):
            ln = f'FROM {BASE}@{BASE_DIGEST} AS official\n'
            n_from += 1
        elif 'pip install' in ln:
            m = re.search(r'pip install (--no-cache-dir )?(.*?)(\s*\\?\s*)$', ln)
            if not m:
                raise ComposeError(f'unexpected pip line: {ln!r}')
            pkgs = m.group(2).split()
            pinned = []
            for p in pkgs:
                if '==' in p or p.startswith('-'):
                    pinned.append(p)
                elif p in PIP_PINS:
                    pinned.append(f'{p}=={PIP_PINS[p]}')
                else:
                    raise ComposeError(f'unpinned package {p!r} not in PIP_PINS')
            ln = ln[:m.start(2)] + ' '.join(pinned) + m.group(3)
            n_pip += 1
        out.append(ln)
    if n_from != 1 or n_pip != 1:
        raise ComposeError(f'expected exactly one `FROM {BASE}` and one pip install line, got {n_from} and {n_pip}')
    return ''.join(out)


def compose(public_path: Path, allow_other_sha: bool = False) -> tuple[str, str]:
    raw = public_path.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    if sha != PUBLIC_SHA256:
        msg = f'{public_path}: sha256 {sha} != expected {PUBLIC_SHA256} (the competition file changed?)'
        if not allow_other_sha:
            raise ComposeError(msg + '; re-run with --allow-other-sha256 to compose anyway')
        print('WARNING: ' + msg, file=sys.stderr)
    public = raw.decode()
    official = pin_official(public)
    fixes = (HERE / 'Dockerfile.fixes').read_text()
    header = ('# GENERATED by harness/sandbox/compose_dockerfile.py: stage "official" = the competition\'s\n'
              f'# docker/Dockerfile.public (sha256 {sha[:16]}...) with pins; stage "final" = Dockerfile.fixes.\n')
    return public, header + official.rstrip('\n') + '\n\n# ' + '-' * 93 + '\n' + fixes


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--public', type=Path, required=True, help='the downloaded docker/Dockerfile.public')
    ap.add_argument('--out', type=Path, help='write the composed Dockerfile here (default: stdout)')
    ap.add_argument('--diff', action='store_true', help='print public -> stage official diff instead')
    ap.add_argument('--allow-other-sha256', action='store_true')
    a = ap.parse_args(argv)
    try:
        public, composed = compose(a.public, a.allow_other_sha256)
    except ComposeError as e:
        print(f'compose_dockerfile: {e}', file=sys.stderr)
        return 2
    if a.diff:
        official = pin_official(public)
        sys.stdout.writelines(difflib.unified_diff(public.splitlines(True), official.splitlines(True),
                                                   'Dockerfile.public', 'stage official'))
        return 0
    if a.out:
        a.out.write_text(composed)
    else:
        sys.stdout.write(composed)
    return 0


if __name__ == '__main__':
    sys.exit(main())
