"""Check harness/subsets/unsound.txt against grades files, and compare it with a community soundness table.

    python -m harness.subsets.compare_unsound --gold data/audit/gold-all/grades.jsonl \\
        --empty data/audit/empty-all/grades.jsonl
    python -m harness.subsets.compare_unsound --community task_soundness.csv [--md out.md]

--gold/--empty: unsound = gold failed OR empty passed; prints the diff against unsound.txt (exit 1 if non-empty).
--community: a CSV with columns task_id and sound (1 = sound), e.g. the CC BY 4.0 task_soundness.csv from
  https://www.kaggle.com/code/dmitriigluzdov/gemma-4-task-soundness-serving-and-evaluation (not redistributed here);
  prints both exclusion counts, the overlap and the symmetric difference.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def read_ids(path: Path) -> list[str]:
    out = []
    for ln in path.read_text().splitlines():
        ln = ln.split('#', 1)[0].strip()
        if ln:
            out.append(ln)
    return out


def from_grades(gold: Path, empty: Path) -> set[str]:
    def rows(p: Path) -> list[dict]:
        return [json.loads(ln) for ln in p.read_text().splitlines() if ln.strip()]
    return {r['instance_id'] for r in rows(gold) if not r['passed']} | {r['instance_id'] for r in rows(empty) if r['passed']}


def community_excluded(csv_path: Path) -> set[str]:
    with open(csv_path, newline='') as f:
        return {r['task_id'] for r in csv.DictReader(f) if str(r.get('sound', '')).strip() != '1'}


def compare(ours: set[str], theirs: set[str]) -> dict:
    return {'ours': len(ours), 'community': len(theirs), 'overlap': len(ours & theirs),
            'only_ours': sorted(ours - theirs), 'only_community': sorted(theirs - ours),
            'symmetric_difference': len(ours ^ theirs)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--unsound', type=Path, default=HERE / 'unsound.txt')
    ap.add_argument('--gold', type=Path)
    ap.add_argument('--empty', type=Path)
    ap.add_argument('--community', type=Path)
    ap.add_argument('--md', type=Path, help='write the community comparison as markdown')
    a = ap.parse_args(argv)
    listed = set(read_ids(a.unsound))
    rc = 0
    if a.gold and a.empty:
        derived = from_grades(a.gold, a.empty)
        missing, extra = sorted(derived - listed), sorted(listed - derived)
        print(f'unsound from grades: {len(derived)}; listed in {a.unsound.name}: {len(listed)}; '
              f'diff: {"none" if not (missing or extra) else f"not listed {missing}, listed but sound {extra}"}')
        rc = 1 if (missing or extra) else 0
    if a.community:
        c = compare(listed, community_excluded(a.community))
        print(f'ours {c["ours"]} vs community {c["community"]}, overlap {c["overlap"]}, '
              f'symmetric difference {c["symmetric_difference"]}')
        print(f'  only ours: {" ".join(c["only_ours"])}\n  only community: {" ".join(c["only_community"])}')
        if a.md:
            a.md.write_text(
                '# Unsound list vs the community soundness table\n\n'
                'Generated by `python -m harness.subsets.compare_unsound --community task_soundness.csv`. Community data: '
                'Dmitrii Gluzdov, "Gemma 4: Task Soundness, Serving and Evaluation", CC BY 4.0, '
                'https://www.kaggle.com/code/dmitriigluzdov/gemma-4-task-soundness-serving-and-evaluation '
                '(`sound != 1` counts as excluded; the CSV is linked, not copied).\n\n'
                f'| | count |\n|---|---|\n| ours (`harness/subsets/unsound.txt`) | {c["ours"]} |\n'
                f'| community excluded | {c["community"]} |\n| overlap | {c["overlap"]} |\n'
                f'| symmetric difference | {c["symmetric_difference"]} |\n\n'
                f'Only ours: {", ".join(c["only_ours"]) or "none"}\n\n'
                f'Only community: {", ".join(c["only_community"]) or "none"}\n')
    if not ((a.gold and a.empty) or a.community):
        ap.error('give --gold and --empty, or --community')
    return rc


if __name__ == '__main__':
    sys.exit(main())
