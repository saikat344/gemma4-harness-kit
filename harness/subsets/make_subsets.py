"""Regenerate the named task subsets (deterministic). Run from the repo root:

    python3 harness/subsets/make_subsets.py [data/kaggle/tasks.jsonl]

dev40: 40 tasks stratified by repo with largest-remainder proportional allocation (every repo gets >= 1),
sampled with random.Random(SEED) from each repo's ids sorted by name. With the public 129 tasks this is
fastapi 20, rich 14, requests 5, httpx 1. all129: every task in tasks.jsonl order.
The runner accepts a subset by name: --task-ids dev40.
"""

from __future__ import annotations

import json
import random
import sys
from collections import defaultdict
from pathlib import Path

SEED = 20261102
DEV_N = 40
HERE = Path(__file__).resolve().parent


def allocate(counts: dict[str, int], n: int) -> dict[str, int]:
    total = sum(counts.values())
    alloc = {r: 1 for r in counts}  # every repo at least once
    rest = n - len(counts)
    quotas = {r: rest * c / total for r, c in counts.items()}
    for r, q in quotas.items():
        alloc[r] += int(q)
    left = n - sum(alloc.values())
    for r in sorted(quotas, key=lambda r: (-(quotas[r] - int(quotas[r])), r))[:left]:
        alloc[r] += 1
    return {r: min(a, counts[r]) for r, a in alloc.items()}


def main() -> None:
    tasks_path = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parents[1] / 'data' / 'kaggle' / 'tasks.jsonl'
    rows = [json.loads(ln) for ln in tasks_path.read_text().splitlines() if ln.strip()]
    by_repo: dict[str, list[str]] = defaultdict(list)
    for r in rows:
        by_repo[r['repo']].append(r['instance_id'])
    alloc = allocate({r: len(v) for r, v in by_repo.items()}, DEV_N)
    rng = random.Random(SEED)
    picked: list[str] = []
    for repo in sorted(by_repo):
        picked += sorted(rng.sample(sorted(by_repo[repo]), alloc[repo]))
    head = (f'# dev40: {DEV_N} public tasks stratified by repo {dict(sorted(alloc.items()))}, seed {SEED}.\n'
            f'# Generated by harness/subsets/make_subsets.py from tasks.jsonl ({len(rows)} rows). Do not hand-edit.\n')
    (HERE / 'dev40.txt').write_text(head + '\n'.join(picked) + '\n')
    (HERE / 'all129.txt').write_text(
        f'# all129: every public task in tasks.jsonl order ({len(rows)} rows). Generated by make_subsets.py.\n'
        + '\n'.join(r['instance_id'] for r in rows) + '\n')
    print(alloc, len(picked))


if __name__ == '__main__':
    main()
